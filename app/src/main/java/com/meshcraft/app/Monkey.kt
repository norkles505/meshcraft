/**
 * Datos de geometria del mono (Suzanne) - toda la infraestructura de OpenGL (shaders, buffers,
 * draw) vive en MeshGeometry.kt, compartida con el resto de las primitivas. Ver MeshGeometry.kt
 * para el porque de este split.
 *
 * A diferencia de Cube/Torus/Grid (geometria generada por formula en el init), aca el mesh viene
 * de un .obj exportado de Blender (Suzanne, 507 vertices / 967 caras, todas triangulos - export
 * con "Triangulated Mesh" tildado para no tener que triangular quads a mano). objVertices y
 * faceIndices son los datos crudos del .obj (posicion de cada vertice + que 3 vertices arma cada
 * triangulo) - se guardan compactos aca (1521 floats / 2901 shorts) en vez de guardar ya
 * "explotados" los ~2900 vertices de caras (lo que usa MeshGeometry para el shading plano),
 * porque el archivo quedaria con miles de floats repetidos sin necesidad; la explosion en
 * triangulos con normal por cara (mismo criterio de sombreado PLANO que Cube/Torus/Grid, no el
 * suave de UvSphere) se calcula una sola vez en el init, igual que ya hace Torus con su grilla.
 *
 * Escala 0.5 ya aplicada a objVertices (ver SCALE al generar los datos): Blender exporta Suzanne
 * con radio ~1.37 en X (su cubo default mide 2, radio 1 - mismo "doble" que el resto de las
 * medidas de Blender comparadas con esta app). El Cube de esta app usa medio-lado 0.5 (radio
 * 0.5*sqrt(3) en la diagonal) para su "unit size 1" (ver Cube.kt) - escalando el mono a la mitad
 * de su tamano original en Blender lo deja proporcionado contra el resto de las primitivas
 * (Cube/UvSphere/etc, todas radio ~0.5) en vez de aparecer el doble de grande.
 *
 * Ejes: el .obj fue exportado desde Blender con el eje "arriba/abajo de la cabeza" (frente
 * arriba, menton abajo) guardado en Y y la protrusion de la cara (nariz hacia adelante) guardada
 * en Z - mapeando Z directo al Z de la app (arriba), la cara terminaba mirando hacia arriba.
 * rawVertices corrige esto combinando tres giros sobre objVertices: primero 90 grados sobre el
 * eje X (x sin cambios, y'=-z, z'=y) para que el eje cabeza-arriba/abajo pase a ser el Z de la
 * app y la protrusion de la cara pase al eje Y; despues, dos giros mas de 90 grados hacia la
 * derecha sobre el eje Z (cada uno x'=y, y'=-x) para terminar de orientar la cara hacia
 * adelante. Los tres giros combinados en uno: (x,y,z) -> (-x,z,y). Calculado una sola vez a
 * partir de objVertices en vez de tocar a mano los 1521 floats crudos.
 *
 * Contorno de seleccion: a diferencia de Cube (aristas fijas, escritas a mano) o Torus/Grid
 * (aristas de una grilla regular, con formula), un mesh arbitrario como este no tiene una
 * estructura de aristas obvia para elegir a mano - se calculan en el init recorriendo las 967
 * caras y juntando sus 3 pares de vertices (a,b)-(b,c)-(c,a) en un Set de pares normalizados
 * (min,max) para no repetir la misma arista dos veces cuando la comparten dos triangulos vecinos
 * (que es case casi siempre, salvo el borde de algun agujero en la malla). 1472 aristas unicas
 * resultan de las 967*3 = 2901 aristas "crudas" (con repeticion) que salen de recorrer cada
 * triangulo. Usa rawVertices (no los explotados) para no dibujar el mismo segmento superpuesto
 * una vez por cada triangulo que lo toca. Mismo edgeScale (1.003) que el resto de las primitivas
 * para que el contorno no quede exactamente pegado a la superficie (z-fighting).
 */

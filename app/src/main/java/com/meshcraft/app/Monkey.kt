    private val rawVertices = FloatArray(objVertices.size).also { arr ->
        for (v in objVertices.indices step 3) {
            val x = objVertices[v]
            val y = objVertices[v + 1]
            val z = objVertices[v + 2]
            arr[v] = -x
            arr[v + 1] = z
            arr[v + 2] = y
        }
    }

    private val edgeScale = 1.003f

    private val faceVertices: FloatArray
    private val faceNormals: FloatArray
    private val faceDrawOrder: ShortArray
    private val edgeVertices: FloatArray
    private val edgeDrawOrder: ShortArray
    private val geometry: MeshGeometry

    init {
        // Explota cada triangulo del .obj en 3 vertices propios con la normal de su cara (cross
        // product de sus 2 aristas) - mismo criterio de sombreado plano que Torus/Cube/Grid.
        val fVerts = mutableListOf<Float>()
        val fNorms = mutableListOf<Float>()

        val triCount = faceIndices.size / 3
        for (t in 0 until triCount) {
            val ia = faceIndices[t * 3].toInt()
            val ib = faceIndices[t * 3 + 1].toInt()
            val ic = faceIndices[t * 3 + 2].toInt()

            val ax = rawVertices[ia * 3]; val ay = rawVertices[ia * 3 + 1]; val az = rawVertices[ia * 3 + 2]
            val bx = rawVertices[ib * 3]; val by = rawVertices[ib * 3 + 1]; val bz = rawVertices[ib * 3 + 2]
            val cx = rawVertices[ic * 3]; val cy = rawVertices[ic * 3 + 1]; val cz = rawVertices[ic * 3 + 2]

            val ux = bx - ax; val uy = by - ay; val uz = bz - az
            val vx = cx - ax; val vy = cy - ay; val vz = cz - az
            var nx = uy * vz - uz * vy
            var ny = uz * vx - ux * vz
            var nz = ux * vy - uy * vx
            val nLen = sqrt(nx * nx + ny * ny + nz * nz)
            if (nLen > 1e-8f) { nx /= nLen; ny /= nLen; nz /= nLen }

            fVerts.addAll(listOf(ax, ay, az, bx, by, bz, cx, cy, cz))
            repeat(3) { fNorms.addAll(listOf(nx, ny, nz)) }
        }

        faceVertices = fVerts.toFloatArray()
        faceNormals = fNorms.toFloatArray()
        faceDrawOrder = ShortArray(faceVertices.size / 3) { it.toShort() }

        // Contorno de seleccion: aristas unicas de la malla (ver comentario de la clase), sobre
        // rawVertices escalados por edgeScale - no sobre los vertices explotados.
        edgeVertices = FloatArray(rawVertices.size) { rawVertices[it] * edgeScale }

        val uniqueEdges = LinkedHashSet<Long>()
        for (t in 0 until triCount) {
            val ia = faceIndices[t * 3].toInt()
            val ib = faceIndices[t * 3 + 1].toInt()
            val ic = faceIndices[t * 3 + 2].toInt()
            for (pair in listOf(ia to ib, ib to ic, ic to ia)) {
                val a = minOf(pair.first, pair.second)
                val b = maxOf(pair.first, pair.second)
                uniqueEdges.add((a.toLong() shl 32) or b.toLong())
            }
        }

        val eOrder = mutableListOf<Short>()
        for (key in uniqueEdges) {
            val a = (key shr 32).toInt()
            val b = (key and 0xFFFFFFFFL).toInt()
            eOrder.add(a.toShort())
            eOrder.add(b.toShort())
        }
        edgeDrawOrder = eOrder.toShortArray()

        geometry = MeshGeometry(faceVertices, faceNormals, faceDrawOrder, edgeVertices, edgeDrawOrder)
    }

    fun draw(mvpMatrix: FloatArray, selected: Boolean) {
        geometry.draw(mvpMatrix, selected)
    }
